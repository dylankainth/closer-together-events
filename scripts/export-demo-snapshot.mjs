// Save the demo personas' current picks into convex/demoSnapshot.ts (the never-empty backup).
// Run with CONVEX_SELF_HOSTED_URL and CONVEX_SELF_HOSTED_ADMIN_KEY set in the shell:
//   node scripts/export-demo-snapshot.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const out = execFileSync("npx", ["convex", "run", "discoveryData:snapshotData", "{}"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
const data = JSON.parse(out.slice(out.indexOf("{")));
const header = `// Generated by scripts/export-demo-snapshot.mjs on ${new Date().toISOString()}: the demo personas' picks
// at a known-good moment, restored by discoveryData.loadSnapshot for any demo persona left with no picks.
import type { Keyed, PickDraft } from "./discoveryCore";

export const DEMO_SNAPSHOT: { events: Keyed[]; picks: (Omit<PickDraft, "key"> & { personaId: string; key: string })[] } = `;
// Team rule: no long dashes in committed files, so scraped text gets plain hyphens.
const LONG_DASH = String.fromCharCode(0x2014);
const body = JSON.stringify(data, null, 1).split(LONG_DASH).join("-");
writeFileSync(new URL("../convex/demoSnapshot.ts", import.meta.url), `${header}${body};\n`);
console.log(`saved ${data.events.length} events and ${data.picks.length} picks`);
